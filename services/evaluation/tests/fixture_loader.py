"""Loads the TS-owned parity fixtures and reconstructs the v2 wire request.

Two fixtures, one per contract generation (OpsPilot #59 Checkpoint A §9):

- `ts-parity-v1.json` — FROZEN. The historical v1 artifact, consumed only by
  the offline v1 oracle in `opspilot_evaluation.legacy_v1` (its SHA-256 is
  pinned by the TypeScript parity-v1.test.ts and never regenerated).
- `ts-parity-v2.json` — the active v2 artifact generated by the TS
  export-parity-vectors script.

Each fixture serves two purposes at once: each case carries the wire-facing
`caseId`/`expectations`/`observed` fields AND a TS-only `expected` field (the
golden check-level output), and the suite carries a TS-only top-level
`expectedMetrics` field. This module is the one place that separates the
wire-facing subset from the golden-comparison subset, so both test packages
(active v2 and frozen v1) read the same fixtures the same way.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

_FIXTURES_DIR = Path(__file__).resolve().parents[3] / "apps" / "worker" / "src" / "evaluation" / "fixtures"

FIXTURE_PATH_V1 = _FIXTURES_DIR / "ts-parity-v1.json"
FIXTURE_PATH_V2 = _FIXTURES_DIR / "ts-parity-v2.json"


def load_fixture_v1() -> dict[str, Any]:
    """Loads the FROZEN v1 fixture (offline oracle only)."""
    with FIXTURE_PATH_V1.open() as f:
        return json.load(f)


def load_fixture_v2() -> dict[str, Any]:
    """Loads the active v2 fixture."""
    with FIXTURE_PATH_V2.open() as f:
        return json.load(f)


def build_wire_request(fixture: dict[str, Any]) -> dict[str, Any]:
    """Reconstructs the EvaluationSuiteInputV2 wire request from a fixture,
    dropping the TS-only `expected` echo on each case. No shape adaptation:
    caseId/expectations/observed are passed through unmodified.
    """
    return {
        "contractVersion": fixture["contractVersion"],
        "datasetId": fixture["datasetId"],
        "cases": [
            {
                "caseId": case["caseId"],
                "expectations": case["expectations"],
                "observed": case["observed"],
            }
            for case in fixture["cases"]
        ],
    }
